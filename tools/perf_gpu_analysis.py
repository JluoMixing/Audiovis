渲染占比 = 渲染每帧 / (渲染每帧 + 编码每帧) * 100
print("  渲染占 %.0f%%（%.1f 秒）" % (渲染占比, 渲染秒))
print("  编码占 %.0f%%（%.1f 秒）" % (编码占比, 编码每帧 * 总帧数 / 1000))
