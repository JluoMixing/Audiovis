基准 = 总耗时
for 名, 每帧 in 场景:
    编码秒 = 每帧 * 总帧数 / 1000
    总 = 渲染秒 + 编码秒
    print("%-22s %12.1f %12.1f %12.2f %11.2f×" % (
        名, 编码秒, 总, 总 / 60, 基准 / 总))

print("%-22s %12.1f %12.1f %12.2f %11s" % (
    "当前（libx264 medium）", 编码每帧 * 总帧数 / 1000, 总耗时, 总耗时 / 60, "1.00×"))

