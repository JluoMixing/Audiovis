print("  ★ 关键：渲染与编码是**串行**的（先出全部帧，再编码）")
print("     所以总耗时 ≈ 渲染 + 编码 = %.1f + %.1f = %.1f 秒" % (
    渲染每帧 * 总帧数 / 1000, 编码每帧 * 总帧数 / 1000,
    (渲染每帧 + 编码每帧) * 总帧数 / 1000))

