方案 = []

# 1. 消除 base64 传输
# base64 有 33% 体积膨胀。CDP 支持 returnByValue=false + 二进制，
# 或用 Page.captureScreenshot 的二进制响应（实际仍返回 base64，
# 但省去 JS 侧字符串拼接）。保守估计省去传输开销的 40%。
省1 = B渲染 * 0.40
方案.append({
    "手段": "二进制帧传输（去掉 base64）",
    "省": 省1,
    "依据": "base64 有 33% 体积膨胀；实测 PNG 编码 16.5ms 中含编码+编码为字符串",
    "难度": "中",
})

# 2. 并行渲染
# 单进程串行 → N 个浏览器进程并行。按 4 核保守估计（实际现代 CPU 8~16 核）
并行度 = 4
省2 = (B渲染 - 省1) * (1 - 1 / 并行度)
方案.append({
    "手段": "多进程并行渲染（%d 路）" % 并行度,
    "省": 省2,
    "依据": "渲染是 CPU 密集且天然可分片（按帧区间切分）",
    "难度": "低",
})

# 3. 硬件编码
# 编码 16ms/帧 → NVENC 约 2~4ms/帧
编码优化后 = 2.5
省3 = B编码 - 编码优化后
方案.append({
    "手段": "硬件编码（NVENC / QSV）",
    "省": 省3,
    "依据": "H.264 硬件编码器通常比 libx264 medium 快 4~8 倍",
    "难度": "低",
})

# 4. 降低 PNG 编码开销：改用更快的方式取帧
# 若能用 GPU 直接读回或跳过 PNG（如 PPM/BMP 无损格式），可再省
省4 = 2.0
方案.append({
    "手段": "改用更快的无损帧格式（PPM/BMP）",
    "省": 省4,
    "依据": "PNG 需 zlib 压缩；PPM 几乎零编码开销，但文件大 3~5 倍",
    "难度": "低",
})

# 5. 只渲染变化区域（增量渲染）
# 组件中只有频谱/波形/步进器每帧变化；主时间轴变化很小。
# 保守估计省 20%。
省5 = (B渲染 - 省1) * 0.20
方案.append({
    "手段": "增量渲染（只重绘变化区域）",
    "省": 省5,
    "依据": "主时间轴每帧变化 <5%，可缓存复用；仅音频类组件需重绘",
    "难度": "高",
})

print("%-34s %10s %10s %8s" % ("手段", "每帧省", "收益占比", "难度"))
print("-" * 68)
