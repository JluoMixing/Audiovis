成功 = [x for x in B if x.get("状态") == "成功"]
B渲染 = sum(x["渲染每帧ms"] for x in 成功) / len(成功)
B编码 = sum(x["编码每帧ms"] for x in 成功) / len(成功)

时长 = 266.0     # nujabes 时长
