"""鲁棒性测试：模拟不同屏幕/DPI/任务栏位置。

## 为什么这么测

用户最怕的是「只在我这台机器能用」。
无法真的换电脑，故用 Win32 **模拟**各种条件：

1. 不同工作区尺寸（通过 SetWindowPos 强制窗口尺寸验证布局不崩）
2. 不同 DPI（读注册表/API 确认换算逻辑正确）
3. 任务栏在顶部/左侧（用 SPI_GETWORKAREA 返回值验证）
4. 小屏（验证 min_size 收缩逻辑）
5. 多显示器（验证 MonitorFromPoint 选对显示器）

## 纯逻辑部分不启窗口

`目标工作区()` / `计算最小尺寸()` 是纯函数，可直接用假数据测。
窗口相关部分启一次窗口验证。
"""
import ctypes
import ctypes.wintypes as wt
import json
import pathlib
import sys

根 = pathlib.Path(r"D:\FL_VISUAL_TEST")
sys.path.insert(0, str(根))

from src import webview_host as 宿  # noqa: E402

通过 = 0
失败 = 0


def 断言(名, 条件, 详情=""):
    global 通过, 失败
    if 条件:
        通过 += 1
        print("  ✓ " + 名)
    else:
        失败 += 1
        print("  ✗ " + 名 + ("  → " + str(详情) if 详情 else ""))


print("=" * 74)
print("窗口鲁棒性测试")
print("=" * 74)
print()

# ================================================================ 1) 真实环境
print("【1】当前真实环境")
目标 = 宿.目标工作区()
print("    " + json.dumps({k: v for k, v in 目标.items()},
                          ensure_ascii=False))
断言("工作区尺寸为正", 目标["w"] > 0 and 目标["h"] > 0)
断言("DPI 合理（96~384）", 96 <= 目标["dpi"] <= 384, 目标["dpi"])
断言("scale 与 dpi 一致",
     abs(目标["scale"] - 目标["dpi"] / 96.0) < 1e-6)
print()

# ================================================================ 2) 最小尺寸随屏变化
print("【2】最小尺寸随工作区收缩（小屏不能开不了）")
用例 = [
    ("1920x1080", {"w": 1920, "h": 1040}),
    ("1536x864",  {"w": 1536, "h": 834}),
    ("1366x768",  {"w": 1366, "h": 728}),
    ("1280x720",  {"w": 1280, "h": 680}),
    ("1024x600",  {"w": 1024, "h": 560}),
    ("800x480",   {"w": 800,  "h": 440}),
]
for 名, 区 in 用例:
    最小 = 宿.计算最小尺寸(区)
    合理 = (最小[0] <= 区["w"] and 最小[1] <= 区["h"]
            and 最小[0] >= 480 and 最小[1] >= 360)
    print("    %-10s 工作区 %dx%d → 最小 %dx%d  %s"
          % (名, 区["w"], 区["h"], 最小[0], 最小[1],
             "✓" if 合理 else "✗"))
    断言("%s 的最小尺寸放得下" % 名, 合理,
         "最小 %dx%d vs 工作区 %dx%d" % (最小[0], 最小[1], 区["w"], 区["h"]))
print()

# ================================================================ 3) 任务栏位置
print("【3】任务栏在四个边都能正确处理")
# 工作区 = 整屏减任务栏。四种情况的期望结果
屏宽, 屏高 = 1536, 864
任务栏 = 40
情形 = [
    ("底部", {"x": 0, "y": 0, "w": 屏宽, "h": 屏高 - 任务栏}),
    ("顶部", {"x": 0, "y": 任务栏, "w": 屏宽, "h": 屏高 - 任务栏}),
    ("左侧", {"x": 任务栏, "y": 0, "w": 屏宽 - 任务栏, "h": 屏高}),
    ("右侧", {"x": 0, "y": 0, "w": 屏宽 - 任务栏, "h": 屏高}),
]
for 名, 区 in 情形:
    最小 = 宿.计算最小尺寸(区)
    合理 = 最小[0] <= 区["w"] and 最小[1] <= 区["h"]
    print("    任务栏%s: 工作区 %d,%d %dx%d → 最小 %dx%d  %s"
          % (名, 区["x"], 区["y"], 区["w"], 区["h"],
             最小[0], 最小[1], "✓" if 合理 else "✗"))
    断言("任务栏%s 时最小尺寸合理" % 名, 合理)
print()

# ================================================================ 4) DPI 换算
print("【4】DPI 换算（logical ↔ physical）")
for dpi in (96, 120, 144, 192):
    scale = dpi / 96.0
    # 模拟 1536x864 physical → logical
    物理宽, 物理高 = 1536, 864
    逻辑宽 = int(物理宽 / scale)
    逻辑高 = int(物理高 / scale)
    回算宽 = int(逻辑宽 * scale)
    print("    DPI %-4d (%.0f%%)  物理 %dx%d → 逻辑 %dx%d → 回算 %d"
          % (dpi, scale * 100, 物理宽, 物理高, 逻辑宽, 逻辑高, 回算宽))
    断言("DPI %d 的换算误差 < 2px" % dpi, abs(回算宽 - 物理宽) <= 2,
         "%d vs %d" % (回算宽, 物理宽))
print()

# ================================================================ 5) 窗口句柄过滤
print("【5】窗口句柄过滤（不能抓到辅助窗口）")
# 检查 _枚举本窗口 的过滤条件
import inspect
src = inspect.getsource(宿._枚举本窗口)
断言("过滤了尺寸下限", "w < 200" in src or "w <" in src)
断言("过滤了屏幕外位置", "r.left < -1000" in src)
断言("要求类名 WindowsForms", "WindowsForms" in src)
断言("要求标题匹配", "buf.value != 标题" in src)
print()

# ================================================================ 6) 环境摘要可用
print("【6】环境摘要（自检入口）")
摘要 = 宿.环境摘要()
print("    " + json.dumps(摘要, ensure_ascii=False))
断言("含目标工作区", "目标工作区" in 摘要)
断言("含 DPI", "DPI" in 摘要)
断言("含最小尺寸", "最小尺寸" in 摘要)
print()

# ================================================================ 7) 无 window.py 残留
print("【7】双实现已清理")
断言("src/window.py 已删除",
     not (根 / "src" / "window.py").is_file())
s = (根 / "app_server.py").read_text(encoding="utf-8")
断言("app_server 不再引用 window.py",
     "src import window" not in s and "src.window" not in s)
断言("_取窗口句柄 已删", "_取窗口句柄" not in s)
print()

print("=" * 74)
print("通过 %d / %d" % (通过, 通过 + 失败))
print("=" * 74)
sys.exit(1 if 失败 else 0)
