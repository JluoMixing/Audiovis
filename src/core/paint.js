/* ============================================================
   组件实例绘制（预览与导出**共用**）
   ------------------------------------------------------------
   ## 为什么必须共用

   此前预览与导出是两套代码：
     预览  DOM 里每个组件一个 canvas，逐组件画底板与柔化，超采样
     导出  整帧一张 canvas，整帧只画一次底板，且不支持文字

   结果是**所见非所得**：在 GUI 里调好的逐组件柔化、文字样式，
   导出后拿不到。这个不解决，导出就没有意义。

   故把「画一个组件实例」抽成这一个函数，
   GUI 预览与渲染管线都调它 —— 只有一处实现，不可能不一致。

   ## 约定

   调用者负责摆好坐标系：**原点 = 组件左上角，单位 = 目标尺寸像素**。
     · 预览：canvas 按 p.w×倍率 建好后 g.scale(倍率)，再调本函数
     · 导出：g.translate(item.x, item.y) 后调本函数
   本函数内部自己处理「注册尺寸 → 目标尺寸」的换算。

   ## 两条路径（历史教训）

   组件分两类，缩放语义不同：

     ① 位图式（频谱/波形/时间轴…）
        内容是「按固定尺寸设计的图」，拉伸合理。
        路径：按注册尺寸绘制 → scale(目标/注册)

     ② 矢量式（文字）
        内容是字形，非等比缩放会**拉伸字形**。
        实测：只有框比例 = 注册比例(3.10) 时不变形，
             其余 10/11 种尺寸组合都会拉伸。
        路径：**直接在目标尺寸上绘制**，不经过任何 scale

   这正是用户报告「文字只有某个特定大小才正常」的根因。
   ============================================================ */

/* 是否矢量式组件（决定走哪条路径） */
function 是矢量组件(id) { return id === 'text'; }

/* ---- 实例级「窗口大小」（小节数） ----
   ------------------------------------------------------------
   用户要求把主时间轴/步进器/钢琴卷帘/频谱/波形的窗口大小
   放到组件属性里逐个调整。

   组件签名是 draw(g,w,h)，不接收实例参数，故沿用已有的
   「模块级状态 + 绘制前后设/复位」模式（与 设柔化 / 设组件文字 一致）。

   不设时（null）退回各组件自己的默认值 ——
   保证旧的布局、旧的导出结果行为不变。 */
let 当前窗口小节 = null;
function 设窗口(v) {
  当前窗口小节 = (v === undefined) ? null : v;
}
function 窗口小节(默认值) {
  return (当前窗口小节 === null || 当前窗口小节 === undefined)
    ? 默认值 : 当前窗口小节;
}

/* 在给定上下文里绘制一个组件实例。
   p: { id, w, h, 柔化, 隐藏文字, 样式 }
   返回 true 表示成功绘制。 */
function 绘制组件实例(g, p) {
  const comp = COMPONENTS.filter(function (c) { return c.id === p.id; })[0];
  if (!comp) return false;

  const 柔 = (p.柔化 === undefined) ? null : p.柔化;

  try {
    if (是矢量组件(p.id)) {
      /* ---- 路径 ②：直接在目标尺寸上绘制 ---- */
      /* 样式取组件自身的默认值兜底 ——
         不用 GUI 里的 文字默认样式()，因为导出页没有那个函数 */
      const 样式 = p.样式 ||
        (comp.默认 ? Object.assign({}, comp.默认) : {});
      /* 文字默认无底板；开启「底板」时才画（加卡片底会像输入框） */
      if (样式.背景) {
        设柔化(柔);
        panelBackground(g, p.w, p.h);
        设柔化(null);
      }
      /* 显式传样式，不改写 comp.默认 ——
         那是共享对象，改写会让样式泄漏到其它文字元素（踩过一次） */
      if (comp.绘制) comp.绘制(g, p.w, p.h, 样式);
      else comp.draw(g, p.w, p.h);
    } else {
      /* ---- 路径 ①：按注册尺寸绘制后缩放到目标 ---- */
      const 原W = comp.w, 原H = comp.h;
      g.save();
      g.scale(p.w / 原W, p.h / 原H);
      设柔化(柔);
      panelBackground(g, 原W, 原H);
      设柔化(null);
      设窗口(p.窗口);
      /* 组件内文字开关 */
      设组件文字(!p.隐藏文字);
      try {
        无文字绘制(g, function () { comp.draw(g, 原W, 原H); });
      } finally {
        设组件文字(true);        /* 复位，避免影响下一个组件 */
      }
      g.restore();
    }
    return true;
  } catch (e) {
    console.error('[' + p.id + ']', e);
    return false;
  } finally {
    设柔化(null);
    设组件文字(true);
    设窗口(null);      /* 复位，避免影响下一个组件 */
  }
}

/* 整帧绘制一个布局（导出路径用）。
   layout: [{ id, x, y, w, h, 柔化, 隐藏文字, 样式 }, ...]
   opt: { w, h, 背景 } 背景=false 时不铺底色

   ## 底色必须是**纯 bg**，不是底板
   初版这里调 panelBackground(g, W, H)，给整帧铺了一层表面色 + 四边柔化；
   而 GUI 预览是「画布纯 bg + 每个组件各自一块底板」。
   两者结构不同 → 导出与预览逐像素比对时背景区差 3.07，
   文字区差 8.65（0.96 alpha 的字形压在不同底色上，合成结果必然不同）。

   实测确认：改成纯 bg 后差异塌缩（见 tools/test_parity.mjs）。
   这也是「所见即所得」的关键 —— 导出必须复现 GUI 的构成方式。 */
function 绘制布局(g, layout, opt) {
  opt = opt || {};
  const W = opt.w || 0, H = opt.h || 0;
  if (opt.背景 !== false && W && H) {
    g.fillStyle = P.bg;
    g.fillRect(0, 0, W, H);
  }
  (layout || []).forEach(function (item) {
    if (item.hidden) return;

    /* 文字组件允许不给 w/h —— 它的框是「字号与内容的结果」，
       由组件自己的 测量() 算出来（自适应模式）。
       其余组件的尺寸是设计决定的，仍要求显式给出。 */
    let 项 = item;
    if (!item.w || !item.h) {
      const spec = COMPONENTS.filter(function (c) {
        return c.id === item.id;
      })[0];
      if (!spec || typeof spec.测量 !== 'function') return;
      try {
        /* **右侧可用宽**：从 item.x 到画布右边界的距离。
           ------------------------------------------------------------
           问题：文字框按文本实际宽度算，若 x 靠右（如 1432），
           框会伸出画布右边界，文字被裁掉（标题少字母）。

           故把「可用宽」传给 测量()，让它按这个宽度排版；
           若文本仍超宽，再走 text.js 的字号自适应缩字号。 */
        const 右界 = (W && item.x != null) ? Math.max(20, W - item.x) : 0;
        const 尺寸 = spec.测量(item.样式 || {}, 右界);
        if (!尺寸 || !尺寸.w || !尺寸.h) return;
        /* 框宽不能超过右边界 */
        const 框宽 = 右界 > 0 ? Math.min(尺寸.w, 右界) : 尺寸.w;
        项 = Object.assign({}, item, { w: 框宽, h: 尺寸.h });
      } catch (e) {
        return;
      }
    }

    g.save();
    g.translate(项.x, 项.y);
    绘制组件实例(g, 项);
    g.restore();
  });
}
