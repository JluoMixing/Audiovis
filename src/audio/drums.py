"""新建 src/audio/drums.py —— 鼓组识别与分行。

## 设计（与用户敲定）

1. **纳入判定**（哪些 pattern 进步进器）
   · 通道名关键词（现有逻辑，对命名规范的工程够用）
   · MIDI 音高落在 GM 鼓范围（35..59）→ 软音源（如 EZdrummer）
   · pattern / 通道名带 `#step` 后缀 → 强制纳入
   · 音频 clip 默认**不纳入**；名字带 `#step` 才纳入
2. **分行**（不靠名字，靠频率 + 节奏位置）
   · 每个「音高」（或无名通道）是一行
   · 打分决定它排第几行：
       频率分：音高越低 → 越像底鼓，越靠前
       节奏分：落在 1/3 拍偏底鼓；落在 2/4 拍偏军鼓；
               高密度（每半拍）偏踩镲
3. **重合合并**
   · 同一绝对时刻 ±1/16 内、且被判为同一「行」的音符合并成一个
4. **行名一律不输出**（用户要求，避免猜错）

## 为什么不用通道名认鼓件

实测 island：鼓组全在 EZdrummer 软音源里，通道名是软件名，
`_鼓组分类` 必然返回 other。而音高分布很清晰：

    G#3  每半拍      → 踩镲
    D3   2/4 位      → 军鼓
    A#2  1/3 位      → 底鼓

故按「音高 → 频率 + 节奏位置 → 行序」判断，不依赖名字。
"""
import math

# GM 打击乐音高范围（35..59）。软音源的鼓音符绝大多数落在这里。
GM_LOW, GM_HIGH = 35, 59

# 音名 → 半音序号
_音名 = {"C": 0, "C#": 1, "Db": 1, "D": 2, "D#": 3, "Eb": 3, "E": 4,
         "F": 5, "F#": 6, "Gb": 6, "G": 7, "G#": 8, "Ab": 8, "A": 9,
         "A#": 10, "Bb": 10, "B": 11}


def 音名到midi(v):
    """'G#3' → 56（FL 约定 C5=72）。已是数字则原样返回。"""
    if v is None:
        return None
    if isinstance(v, (int, float)):
        return int(v)
    s = str(v).strip()
    if not s:
        return None
    try:
        return int(float(s))
    except ValueError:
        pass
    八度 = None
    音 = None
    for i in range(len(s) - 1, -1, -1):
        if s[i].lstrip("-").isdigit():
            八度 = int(s[i:])
            音 = s[:i]
            break
    if 音 is None or 八度 is None:
        return None
    if 音 not in _音名:
        return None
    return 12 + 八度 * 12 + _音名[音]      # C5=72 ⇒ C0=12


def midi到频率(m):
    if m is None:
        return None
    return 440.0 * (2 ** ((m - 69) / 12.0))


def 有后缀(名称, 后缀="#step"):
    return bool(名称) and 后缀 in str(名称)


def 去后缀(名称, 后缀="#step"):
    if not 名称:
        return 名称
    return str(名称).replace(后缀, "").strip()


def 是打击音高(m):
    return m is not None and GM_LOW <= m <= GM_HIGH


def 节奏特征(位置列表, 每小节步数=16):
    """从音符的「步位置」判断它更像哪类鼓件。

    位置 = 音符在 pattern 内的 16 分步序号（0..15 为一个循环）。

    返回 { 位置集合, 覆盖步数, 正拍占比, 反拍占比, 八分占比 }

      「正拍」= 1、3 拍（步 0、8）
      「反拍」= 2、4 拍（步 4、12）
      「八分」= 落在偶数步的比例（越接近 1 越像 hihat）
    """
    if not 位置列表:
        return {"覆盖步数": 0, "正拍比": 0.0, "反拍比": 0.0, "八分比": 0.0,
                "每小节": 0.0}
    步 = set(p % 每小节步数 for p in 位置列表)
    总数 = len(位置列表)
    正拍 = sum(1 for p in 位置列表 if (p % 每小节步数) in (0, 8))
    反拍 = sum(1 for p in 位置列表 if (p % 每小节步数) in (4, 12))
    八分 = sum(1 for p in 位置列表 if (p % 2) == 0)
    # 每小节平均几次 —— 这才是判断「密/疏」的可靠指标。
    # 「八分比」对稀疏音符会误判：A#2 只落在步 0/10/14（都是偶数），
    # 八分比 = 1.00，看起来和 hihat 一样密集，实际一拍才一次。
    跨度 = max(位置列表) - min(位置列表) if len(位置列表) > 1 else 每小节步数
    小节数 = max(1.0, (跨度 + 每小节步数) / float(每小节步数))
    return {
        "覆盖步数": len(步),
        "位置": sorted(步),
        "正拍比": 正拍 / 总数,
        "反拍比": 反拍 / 总数,
        "八分比": 八分 / 总数,
        "每小节": round(总数 / 小节数, 2),
    }


def 行序评分(midi, 节奏, 每小节步数=16):
    """给一行打分，分数越小越靠前（底鼓 → 军鼓 → 踩镲）。

    ## 为什么不能只用「正拍比/反拍比」

    实测 island 的 amen break（EZdrummer）：
        军鼓 D3  —— 落在步 0、4、8、12 → 正拍比 0.47、反拍比 0.00
        底鼓 A#2 —— 落在步 0、10、14   → 正拍比 0.44、反拍比 0.00

    两者正拍比接近、都没有反拍，「反拍比 > 正拍比 → 军鼓」这条规则
    完全没生效，结果军鼓排到了底鼓前面。

    真正能分开它们的是**事件密度**：
        kick   稀疏（一拍一次或更少）
        snare  更稀疏，但位置固定
        hihat  密集（每半拍）

    ## 现在的判据（频率为主，密度/位置为辅）

    1) 频率分：MIDI 35 → 0，60 → 1。音高是最硬的信息，权重 0.55。
    2) 密度分：
         · 八分比 > 0.85 → 密集，像踩镲 → 1.0
         · 覆盖步数 ≤ 4  → 稀疏（一击一记）→ 0.25
         · 否则按覆盖步数线性过渡
       权重 0.30。
    3) 位置分：2、4 拍（反拍）权重高 → 像军鼓 → 1.0；
       只有 1、3 拍 → 像底鼓 → 0.0。权重 0.15。

    这样 kick(46Hz 档 + 稀疏) 会稳定排在 snare(50 档 + 稀疏) 之前，
    hihat(56 档 + 密集) 排最后。
    """
    if midi is None:
        频 = 0.5
    else:
        频 = max(0.0, min(1.0, (midi - GM_LOW) / float(GM_HIGH - GM_LOW)))

    正拍比 = 节奏.get("正拍比", 0.0)
    反拍比 = 节奏.get("反拍比", 0.0)
    每小节 = 节奏.get("每小节", 0.0)

    # 密度分：按「每小节平均几次」
    #   ≥ 8 次（每半拍）      → 1.0   踩镲
    #   ≤ 4 次（一拍一次或更少）→ 0.2   底鼓/军鼓
    #   中间线性过渡
    if 每小节 >= 8:
        密度 = 1.0
    elif 每小节 <= 4:
        密度 = 0.2
    else:
        密度 = 0.2 + (每小节 - 4) / 4.0 * 0.8

    # 位置分：反拍多 → 军鼓；纯正拍 → 底鼓
    if 反拍比 > 0.15:
        位置 = 1.0
    elif 正拍比 > 0.3 and 反拍比 < 0.05:
        位置 = 0.0
    else:
        位置 = 0.5

    return 0.55 * 频 + 0.30 * 密度 + 0.15 * 位置

def 合并重合(行数据, 容差=1):
    """把同一绝对时刻（±容差 tick）内的音符合并。

    容差默认 1 个 16 分音符（PPQ/4）由调用方传入。
    合并规则：保留力度最大的那个，其余标记为「被合并」。
    """
    结果 = []
    按时刻 = {}
    for 项 in 行数据:
        k = round(项["absTick"] / float(容差))
        桶 = 按时刻.setdefault(k, [])
        桶.append(项)
    for k in sorted(按时刻):
        桶 = 按时刻[k]
        最好 = max(桶, key=lambda x: (x.get("vel") or 0))
        最好 = dict(最好)
        最好["merged"] = len(桶)
        结果.append(最好)
    return 结果
